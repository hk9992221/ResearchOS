/**
 * Bundle containers: streamed writers for folder/zip/tar.gz and read-only
 * walkers for the same three. Every copy is bounded by `CHUNK_SIZE` (1 MiB) and
 * hashed in the same pass that writes it, so no file is ever loaded whole.
 *
 * Writers never publish in place: the folder writer fills a staging directory
 * and the archive writers fill `<dest>/.<base>.<ext>.part`; `publish` renames
 * the finished artifact only after `finish()` succeeded.
 */
import { createHash } from 'node:crypto'
import {
  closeSync,
  createReadStream,
  createWriteStream,
  fsyncSync,
  lstatSync,
  mkdirSync,
  openSync,
  readSync,
  readdirSync,
  rmSync,
  statSync,
  writeSync
} from 'node:fs'
import * as path from 'node:path'
import { open } from 'node:fs/promises'
import { Transform } from 'node:stream'
import { pipeline } from 'node:stream/promises'
import { createGunzip, createGzip } from 'node:zlib'

import { Unzip, UnzipInflate, Zip, ZipDeflate, ZipPassThrough } from 'fflate'
import * as tar from 'tar-stream'

import { AppErrorCode } from '@researchos/shared'

import { appError } from '../../errors'
import { deferred } from './deferred'
import type { ExportFormat, FileKind, ImportFormat } from './types'
import { CHUNK_SIZE, MAX_BUNDLE_FILE_BYTES, MAX_BUNDLE_TOTAL_BYTES } from './types'

export interface WrittenEntry {
  sha256: string
  bytes: number
}

export interface BundleSink {
  /** Streams one source file into the bundle. */
  addFile(bundlePath: string, sourceAbs: string, kind: FileKind, signal?: AbortSignal): Promise<WrittenEntry>
  /** Writes generated bytes (meta JSON / manifest). */
  addBytes(bundlePath: string, data: Buffer): Promise<WrittenEntry>
  /** Finishes the container; after this the artifact is complete but unpublished. */
  finish(): Promise<void>
  /** SHA-256 of the compressed archive bytes (archive formats only). */
  archiveSha256(): string | null
  /** Releases file handles after a failure. */
  abort(): void
}

export const FILE_MODE = 0o644
export const DIR_MODE = 0o755

function throwIfAborted(signal: AbortSignal | undefined): void {
  if (signal?.aborted === true) {
    throw appError(AppErrorCode.Interrupted, 'export: cancelled')
  }
}

export function sha256Hex(data: Buffer | string): string {
  return createHash('sha256').update(data).digest('hex')
}

/** Rejects any bundle path that could escape the bundle root. */
export function validateBundlePath(bundlePath: string): void {
  const invalid =
    bundlePath === '' ||
    bundlePath.startsWith('/') ||
    bundlePath.includes('\\') ||
    bundlePath.split('/').some((segment) => segment === '' || segment === '.' || segment === '..')
  if (invalid) {
    throw appError(AppErrorCode.InvalidArgument, `export: invalid bundle path ${JSON.stringify(bundlePath)}`)
  }
}

export function sameOrInside(root: string, target: string): boolean {
  const relative = path.relative(root, target)
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative))
}

function ensureDir(dir: string): void {
  mkdirSync(dir, { recursive: true, mode: DIR_MODE })
}

/** Hashes one file without loading it (used for snapshots and inspection). */
export async function hashFile(file: string, signal?: AbortSignal): Promise<WrittenEntry> {
  const handle = await openRead(file)
  try {
    const hash = createHash('sha256')
    const buffer = Buffer.allocUnsafe(CHUNK_SIZE)
    let bytes = 0
    for (;;) {
      throwIfAborted(signal)
      const { bytesRead } = await handle.read(buffer, 0, buffer.length, null)
      if (bytesRead === 0) break
      hash.update(buffer.subarray(0, bytesRead))
      bytes += bytesRead
    }
    return { sha256: hash.digest('hex'), bytes }
  } finally {
    await handle.close()
  }
}

async function openRead(file: string) {
  return open(file, 'r')
}

async function streamInto(
  sourceAbs: string,
  write: (chunk: Buffer) => Promise<void>,
  signal?: AbortSignal
): Promise<WrittenEntry> {
  const handle = await openRead(sourceAbs)
  try {
    const hash = createHash('sha256')
    const buffer = Buffer.allocUnsafe(CHUNK_SIZE)
    let bytes = 0
    for (;;) {
      throwIfAborted(signal)
      const { bytesRead } = await handle.read(buffer, 0, buffer.length, null)
      if (bytesRead === 0) break
      const chunk = buffer.subarray(0, bytesRead)
      hash.update(chunk)
      bytes += bytesRead
      await write(Buffer.from(chunk))
    }
    return { sha256: hash.digest('hex'), bytes }
  } finally {
    await handle.close()
  }
}

/* ------------------------------------------------------------------ folder */

export class FolderSink implements BundleSink {
  constructor(readonly root: string) {
    ensureDir(root)
  }

  /** Maps a bundle path into the staging tree, creating its parents. */
  placePath(bundlePath: string): string {
    validateBundlePath(bundlePath)
    const destination = path.join(this.root, ...bundlePath.split('/'))
    if (!sameOrInside(this.root, destination)) {
      throw appError(AppErrorCode.InvalidArgument, `export: bundle path ${JSON.stringify(bundlePath)} escapes staging`)
    }
    ensureDir(path.dirname(destination))
    return destination
  }

  async addFile(bundlePath: string, sourceAbs: string): Promise<WrittenEntry> {
    const destination = this.placePath(bundlePath)
    const info = statSync(sourceAbs)
    const handle = openSync(destination, 'w')
    try {
      const written = await streamInto(sourceAbs, async (chunk) => {
        writeSync(handle, chunk)
      })
      fsyncSync(handle)
      if (written.bytes !== info.size) {
        throw appError(AppErrorCode.Integrity, `export: ${bundlePath} changed during copy`, {
          path: bundlePath
        })
      }
      return written
    } finally {
      closeSync(handle)
    }
  }

  async addBytes(bundlePath: string, data: Buffer): Promise<WrittenEntry> {
    const destination = this.placePath(bundlePath)
    const handle = openSync(destination, 'w')
    try {
      writeSync(handle, data)
      fsyncSync(handle)
    } finally {
      closeSync(handle)
    }
    return { sha256: sha256Hex(data), bytes: data.length }
  }

  async finish(): Promise<void> {
    return Promise.resolve()
  }

  archiveSha256(): string | null {
    return null
  }

  abort(): void {
    rmSync(this.root, { recursive: true, force: true })
  }
}

/* --------------------------------------------------------------------- zip */

function zipEntryName(prefix: string, bundlePath: string): string {
  validateBundlePath(bundlePath)
  return `${prefix}${bundlePath}`
}

export class ZipSink implements BundleSink {
  private readonly handle: number
  private readonly zip: Zip
  private readonly hash = createHash('sha256')
  private closed = false
  private finished = false

  constructor(readonly partPath: string, private readonly prefix: string) {
    rmSync(partPath, { force: true })
    ensureDir(path.dirname(partPath))
    this.handle = openSync(partPath, 'w')
    this.zip = new Zip((error, chunk) => {
      if (error !== null) throw error
      this.hash.update(chunk)
      writeSync(this.handle, chunk)
    })
  }

  async addFile(bundlePath: string, sourceAbs: string, kind: FileKind, signal?: AbortSignal): Promise<WrittenEntry> {
    throwIfAborted(signal)
    const info = statSync(sourceAbs)
    const name = zipEntryName(this.prefix, bundlePath)
    const file =
      kind === 'paper_pdf' || path.extname(bundlePath).toLowerCase() === '.pdf'
        ? new ZipPassThrough(name)
        : new ZipDeflate(name, { level: 6 })
    file.mtime = info.mtime
    this.zip.add(file)
    const written = await streamInto(
      sourceAbs,
      async (chunk) => {
        file.push(chunk, false)
      },
      signal
    )
    file.push(new Uint8Array(0), true)
    if (written.bytes !== info.size) {
      throw appError(AppErrorCode.Integrity, `export: ${bundlePath} changed during copy`, { path: bundlePath })
    }
    return written
  }

  async addBytes(bundlePath: string, data: Buffer): Promise<WrittenEntry> {
    const name = zipEntryName(this.prefix, bundlePath)
    const file = new ZipDeflate(name, { level: 6 })
    file.mtime = new Date()
    this.zip.add(file)
    file.push(new Uint8Array(data.buffer, data.byteOffset, data.byteLength), true)
    return { sha256: sha256Hex(data), bytes: data.length }
  }

  async finish(): Promise<void> {
    if (this.finished) return
    this.finished = true
    this.zip.end()
    fsyncSync(this.handle)
    closeSync(this.handle)
    this.closed = true
  }

  archiveSha256(): string | null {
    return this.hash.digest('hex')
  }

  abort(): void {
    try {
      if (!this.closed) {
        this.zip.terminate()
        closeSync(this.handle)
        this.closed = true
      }
    } catch {
      // The handle may already be gone after a failed finish.
    }
    rmSync(this.partPath, { force: true })
  }
}

/* ------------------------------------------------------------------ tar.gz */

export class TarGzSink implements BundleSink {
  private readonly pack = tar.pack()
  private readonly hash = createHash('sha256')
  private readonly done: Promise<void>
  private finished = false

  constructor(readonly partPath: string, private readonly prefix: string) {
    rmSync(partPath, { force: true })
    ensureDir(path.dirname(partPath))
    const tap = new Transform({
      transform: (chunk: Buffer, _encoding, callback) => {
        this.hash.update(chunk)
        callback(null, chunk)
      }
    })
    this.done = pipeline(this.pack, createGzip({ level: 1 }), tap, createWriteStream(partPath))
    // A failed pipeline rejects `done`; attach a handler so the rejection is
    // observed even when a caller aborts before `finish()` awaits it.
    void this.done.catch(() => undefined)
  }

  async addFile(bundlePath: string, sourceAbs: string, _kind: FileKind, signal?: AbortSignal): Promise<WrittenEntry> {
    throwIfAborted(signal)
    const info = statSync(sourceAbs)
    const entry = this.pack.entry({
      name: zipEntryName(this.prefix, bundlePath),
      type: 'file',
      size: info.size,
      mode: FILE_MODE,
      mtime: info.mtime
    })
    const written = await streamInto(
      sourceAbs,
      async (chunk) => {
        if (!entry.write(chunk)) {
          const drained = deferred<void>()
          entry.once('drain', drained.resolve)
          await drained.promise
        }
      },
      signal
    )
    const ended = deferred<void>()
    entry.end((error?: Error | null) => (error === undefined || error === null ? ended.resolve() : ended.reject(error)))
    await ended.promise
    if (written.bytes !== info.size) {
      throw appError(AppErrorCode.Integrity, `export: ${bundlePath} changed during copy`, { path: bundlePath })
    }
    return written
  }

  async addBytes(bundlePath: string, data: Buffer): Promise<WrittenEntry> {
    const written = deferred<void>()
    this.pack.entry(
      {
        name: zipEntryName(this.prefix, bundlePath),
        type: 'file',
        size: data.length,
        mode: FILE_MODE,
        mtime: new Date()
      },
      data,
      (error?: Error | null) =>
        error === undefined || error === null ? written.resolve() : written.reject(error)
    )
    await written.promise
    return { sha256: sha256Hex(data), bytes: data.length }
  }

  async finish(): Promise<void> {
    if (this.finished) return
    this.finished = true
    this.pack.finalize()
    await this.done
  }

  archiveSha256(): string | null {
    return this.hash.digest('hex')
  }

  abort(): void {
    this.pack.destroy()
    rmSync(this.partPath, { force: true })
  }
}

export interface CreatedSink {
  sink: BundleSink
  /** Empty for the folder format; the archive part file otherwise. */
  partPath: string
}

export function createSink(format: ExportFormat, staging: string, destDir: string, base: string): CreatedSink {
  if (format === 'folder') return { sink: new FolderSink(staging), partPath: '' }
  const extension = format === 'zip' ? '.zip' : '.tar.gz'
  const partPath = path.join(destDir, `.${base}${extension}.part`)
  if (format === 'zip') return { sink: new ZipSink(partPath, `${base}/`), partPath }
  return { sink: new TarGzSink(partPath, `${base}/`), partPath }
}

/* ----------------------------------------------------------------- reading */

export interface BundleEntryVisitor {
  start(bundlePath: string, size: number | undefined): void
  chunk(bundlePath: string, chunk: Uint8Array): void
  end(bundlePath: string, bytes: number, sha256: string): void
  /** A bundle directory entry; archives may omit them. */
  directory?(bundlePath: string): void
}

export function detectBundleFormat(sourcePath: string): ImportFormat {
  const info = statSync(sourcePath)
  if (info.isDirectory()) return 'folder'
  const lower = sourcePath.toLowerCase()
  if (lower.endsWith('.zip')) return 'zip'
  if (lower.endsWith('.tar.gz') || lower.endsWith('.tgz')) return 'tar.gz'
  throw appError(
    AppErrorCode.InvalidArgument,
    `${path.basename(sourcePath)} is neither a folder nor a .zip/.tar.gz archive`,
    { source_path: sourcePath }
  )
}

/** Lists bundle-relative names; the caller detects the single archive prefix. */
export async function listBundle(sourcePath: string, format: ImportFormat): Promise<string[]> {
  const names: string[] = []
  await walkBundle(sourcePath, format, {
    start: (bundlePath) => {
      names.push(bundlePath)
    },
    chunk: () => undefined,
    end: () => undefined
  })
  return names
}

/** Detects the single top-level folder an exporter-made archive carries. */
export function detectArchivePrefix(names: readonly string[], sourcePath: string): string {
  let prefix: string | null = null
  let found = false
  for (const name of names) {
    if (name === 'manifest.json') {
      if (found && prefix !== null && prefix !== '') {
        throw appError(AppErrorCode.InvalidArgument, 'bundle has several roots', { source_path: sourcePath })
      }
      prefix = ''
      found = true
      continue
    }
    if (name.endsWith('/manifest.json') && name.split('/').length === 2) {
      const candidate = name.slice(0, name.length - 'manifest.json'.length)
      if (found && prefix !== candidate) {
        throw appError(AppErrorCode.InvalidArgument, 'bundle has several roots', { source_path: sourcePath })
      }
      prefix = candidate
      found = true
    }
  }
  if (!found) {
    throw appError(AppErrorCode.InvalidArgument, 'bundle is missing manifest.json', {
      source_path: sourcePath
    })
  }
  const resolved = prefix ?? ''
  if (resolved !== '') {
    for (const name of names) {
      if (!name.startsWith(resolved)) {
        throw appError(AppErrorCode.InvalidArgument, `bundle entry ${name} is outside ${resolved}`, {
          source_path: sourcePath
        })
      }
    }
  }
  return resolved
}

/** Walks every file of a bundle in streamed order. */
export async function walkBundle(
  sourcePath: string,
  format: ImportFormat,
  visitor: BundleEntryVisitor,
  signal?: AbortSignal
): Promise<void> {
  switch (format) {
    case 'folder':
      await walkFolder(sourcePath, '', visitor, signal)
      return
    case 'zip':
      await walkZip(sourcePath, '', visitor, signal)
      return
    case 'tar.gz':
      await walkTarGz(sourcePath, '', visitor, signal)
      return
  }
}

/** Walks with a prefix stripped and unsafe entries rejected. */
export async function walkBundlePrefixed(
  sourcePath: string,
  format: ImportFormat,
  prefix: string,
  visitor: BundleEntryVisitor,
  signal?: AbortSignal
): Promise<void> {
  switch (format) {
    case 'folder':
      await walkFolder(sourcePath, prefix, visitor, signal)
      return
    case 'zip':
      await walkZip(sourcePath, prefix, visitor, signal)
      return
    case 'tar.gz':
      await walkTarGz(sourcePath, prefix, visitor, signal)
      return
  }
}

function relativeOf(prefix: string, name: string, sourcePath: string): string | null {
  if (prefix === '') return name
  if (!name.startsWith(prefix)) {
    throw appError(AppErrorCode.InvalidArgument, `bundle entry ${name} is outside ${prefix}`, {
      source_path: sourcePath
    })
  }
  return name.slice(prefix.length)
}

async function walkFolder(
  root: string,
  prefix: string,
  visitor: BundleEntryVisitor,
  signal?: AbortSignal
): Promise<void> {
  const stack: string[] = ['']
  let total = 0
  while (stack.length > 0) {
    throwIfAborted(signal)
    const relativeDir = stack.pop()!
    const absoluteDir = relativeDir === '' ? root : path.join(root, relativeDir)
    const entries = readdirSync(absoluteDir, { withFileTypes: true }).sort((left, right) =>
      left.name.localeCompare(right.name)
    )
    for (const entry of entries) {
      const relative = relativeDir === '' ? entry.name : `${relativeDir}/${entry.name}`
      const absolute = path.join(root, ...relative.split('/'))
      if (entry.isSymbolicLink()) {
        throw appError(AppErrorCode.InvalidArgument, `bundle contains a symbolic link: ${relative}`, {
          source_path: root
        })
      }
      if (entry.isDirectory()) {
        stack.push(relative)
        continue
      }
      if (!entry.isFile()) {
        throw appError(AppErrorCode.InvalidArgument, `bundle contains a non-regular entry: ${relative}`, {
          source_path: root
        })
      }
      const bundlePath = relativeOf(prefix, relative, root)
      const info = lstatSync(absolute)
      if (info.size > MAX_BUNDLE_FILE_BYTES) {
        throw appError(AppErrorCode.InvalidArgument, `bundle entry ${bundlePath} is too large`, {
          source_path: root
        })
      }
      total += info.size
      if (total > MAX_BUNDLE_TOTAL_BYTES) {
        throw appError(AppErrorCode.InvalidArgument, 'bundle exceeds the total size limit', {
          source_path: root
        })
      }
      if (bundlePath === null) continue
      visitor.start(bundlePath, info.size)
      const hash = createHash('sha256')
      let bytes = 0
      const handle = openSync(absolute, 'r')
      try {
        const buffer = Buffer.allocUnsafe(CHUNK_SIZE)
        for (;;) {
          throwIfAborted(signal)
          const read = readSync(handle, buffer, 0, buffer.length, null)
          if (read === 0) break
          const chunk = buffer.subarray(0, read)
          hash.update(chunk)
          bytes += read
          visitor.chunk(bundlePath, chunk)
        }
      } finally {
        closeSync(handle)
      }
      visitor.end(bundlePath, bytes, hash.digest('hex'))
    }
  }
}

async function walkZip(
  sourcePath: string,
  prefix: string,
  visitor: BundleEntryVisitor,
  signal?: AbortSignal
): Promise<void> {
  const handle = openSync(sourcePath, 'r')
  try {
    const completion = deferred<void>()
    let settled = false
    const fail = (error: unknown): void => {
      if (!settled) {
        settled = true
        completion.reject(error)
      }
    }
    {
      const unzip = new Unzip()
      unzip.register(UnzipInflate)
      unzip.onfile = (file) => {
        try {
          if (file.name.endsWith('/')) {
            const directory = relativeOf(prefix, file.name.slice(0, -1), sourcePath)
            if (directory !== null && visitor.directory !== undefined) visitor.directory(directory)
            file.ondata = () => undefined
            file.start()
            return
          }
          const bundlePath = relativeOf(prefix, file.name, sourcePath)
          if (bundlePath === null) {
            file.ondata = () => undefined
            file.start()
            return
          }
          validateBundlePath(bundlePath)
          visitor.start(bundlePath, file.originalSize)
          const hash = createHash('sha256')
          let bytes = 0
          file.ondata = (error, chunk, final) => {
            if (error !== null) {
              fail(error)
              return
            }
            if (chunk.length > 0) {
              hash.update(chunk)
              bytes += chunk.length
              visitor.chunk(bundlePath, chunk)
            }
            if (final) visitor.end(bundlePath, bytes, hash.digest('hex'))
          }
          file.start()
        } catch (error) {
          fail(error)
        }
      }
      try {
        const buffer = Buffer.allocUnsafe(CHUNK_SIZE)
        for (;;) {
          throwIfAborted(signal)
          const read = readSync(handle, buffer, 0, buffer.length, null)
          if (read === 0) break
          unzip.push(new Uint8Array(buffer.subarray(0, read)))
          if (settled) break
        }
        unzip.push(new Uint8Array(0), true)
        if (!settled) {
          settled = true
          completion.resolve()
        }
      } catch (error) {
        fail(error)
      }
    }
    await completion.promise
  } finally {
    closeSync(handle)
  }
}

async function walkTarGz(
  sourcePath: string,
  prefix: string,
  visitor: BundleEntryVisitor,
  signal?: AbortSignal
): Promise<void> {
  const extract = tar.extract()
  const input = createReadStream(sourcePath).pipe(createGunzip()).pipe(extract)
  try {
    for await (const entry of extract) {
      throwIfAborted(signal)
      const header = entry.header
      if (header.type === 'directory') {
        const directory = relativeOf(prefix, header.name, sourcePath)
        if (directory !== null && visitor.directory !== undefined) visitor.directory(directory)
        entry.resume()
        continue
      }
      if (header.type === 'symlink' || header.type === 'link') {
        throw appError(AppErrorCode.InvalidArgument, `bundle entry ${header.name} is a link`, {
          source_path: sourcePath
        })
      }
      if (header.type !== 'file' && header.type !== 'contiguous-file') {
        throw appError(AppErrorCode.InvalidArgument, `bundle entry ${header.name} is not a regular file`, {
          source_path: sourcePath
        })
      }
      const bundlePath = relativeOf(prefix, header.name, sourcePath)
      if (bundlePath === null) {
        entry.resume()
        continue
      }
      validateBundlePath(bundlePath)
      const declared = header.size ?? 0
      if (declared > MAX_BUNDLE_FILE_BYTES) {
        throw appError(AppErrorCode.InvalidArgument, `bundle entry ${bundlePath} is too large`, {
          source_path: sourcePath
        })
      }
      visitor.start(bundlePath, declared)
      const hash = createHash('sha256')
      let bytes = 0
      for await (const chunk of entry) {
        throwIfAborted(signal)
        // tar-stream types the yielded chunk as unknown; the stream only yields bytes.
        const buffer = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk as Uint8Array)
        hash.update(buffer)
        bytes += buffer.length
        if (bytes > MAX_BUNDLE_FILE_BYTES) {
          throw appError(AppErrorCode.InvalidArgument, `bundle entry ${bundlePath} is too large`, {
            source_path: sourcePath
          })
        }
        visitor.chunk(bundlePath, buffer)
      }
      visitor.end(bundlePath, bytes, hash.digest('hex'))
    }
  } finally {
    input.destroy()
    extract.destroy()
  }
}

/** Reads one small bundle file (manifest/meta) with a hard size cap. */
export async function readBundleFile(
  sourcePath: string,
  format: ImportFormat,
  prefix: string,
  name: string,
  limit: number
): Promise<Buffer> {
  const chunks: Buffer[] = []
  let size = 0
  await walkBundlePrefixed(sourcePath, format, prefix, {
    start: (bundlePath, declared) => {
      if (bundlePath !== name) return
      if (declared !== undefined && declared > limit) {
        throw appError(AppErrorCode.InvalidArgument, `${name} exceeds the ${limit} byte limit`, {
          source_path: sourcePath
        })
      }
    },
    chunk: (bundlePath, chunk) => {
      if (bundlePath !== name) return
      size += chunk.length
      if (size > limit) {
        throw appError(AppErrorCode.InvalidArgument, `${name} exceeds the ${limit} byte limit`, {
          source_path: sourcePath
        })
      }
      chunks.push(Buffer.from(chunk))
    },
    end: () => undefined
  })
  if (chunks.length === 0) {
    throw appError(AppErrorCode.InvalidArgument, `${name} is missing from the bundle`, {
      source_path: sourcePath,
      entry: name
    })
  }
  return Buffer.concat(chunks)
}
