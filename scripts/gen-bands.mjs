#!/usr/bin/env node
// Generates packages/core/src/db/bands.ts from the verbatim SQL migration
// files. The SQL text is embedded (not read at runtime) so a packaged build
// cannot drift from what the tests verified, and so the checksums computed here
// are the same bytes the Go engine recorded in schema_migrations.
//
// Usage: node scripts/gen-bands.mjs [--check]
//   --check  exit 1 when bands.ts is stale instead of rewriting it.

import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const migrationsRoot = join(repoRoot, 'packages/core/src/db/migrations')
const outFile = join(repoRoot, 'packages/core/src/db/bands.ts')

const NAME_PATTERN = /^(\d{4})_([a-z][a-z0-9_]*)\.sql$/

// Version bands (plan Appendix B). Every migration must fall inside one band.
export const BANDS = [
  { id: 'foundation', label: 'foundation', from: 1, to: 99 },
  { id: 'ai', label: 'AI', from: 100, to: 199 },
  { id: 'module', label: 'module business', from: 200, to: 299 },
  { id: 'search', label: 'search', from: 300, to: 349 },
  { id: 'mcp', label: 'MCP', from: 350, to: 399 },
  { id: 'additions', label: 'later additions', from: 400, to: 499 },
  { id: 'rewrite', label: 'rewrite additions', from: 500, to: 599 }
]

function bandFor(version) {
  return BANDS.find((band) => version >= band.from && version <= band.to)
}

export function readSources(kind) {
  const dir = join(migrationsRoot, kind)
  const entries = readdirSync(dir, { withFileTypes: true })
  const sources = []
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.sql')) continue
    const match = NAME_PATTERN.exec(entry.name)
    if (!match) {
      throw new Error(`migration ${kind}/${entry.name} must match <4 digits>_<snake_case>.sql`)
    }
    const version = Number(match[1])
    if (version === 0) throw new Error(`migration ${kind}/${entry.name}: version 0 is reserved`)
    const band = bandFor(version)
    if (!band) throw new Error(`migration ${kind}/${entry.name}: version ${version} is outside every band`)
    const bytes = readFileSync(join(dir, entry.name))
    const text = bytes.toString('utf8')
    if (!text.trim()) throw new Error(`migration ${kind}/${entry.name} is empty`)
    sources.push({
      version,
      name: match[2],
      checksum: createHash('sha256').update(bytes).digest('hex'),
      band: band.id,
      sql: text
    })
  }
  sources.sort((a, b) => a.version - b.version)
  const seen = new Set()
  for (const source of sources) {
    if (seen.has(source.version)) {
      throw new Error(`duplicate migration version ${String(source.version).padStart(4, '0')} in ${kind}`)
    }
    seen.add(source.version)
  }
  return sources
}

function renderBands() {
  const lines = []
  lines.push('// Generated by scripts/gen-bands.mjs from db/migrations/**/*.sql — do not edit.')
  lines.push('// The SQL text is embedded byte-for-byte so checksums match the Go engine.')
  lines.push('')
  lines.push("export type MigrationKind = 'global' | 'project'")
  lines.push('')
  lines.push('export interface MigrationBand {')
  lines.push('  readonly id: string')
  lines.push('  readonly label: string')
  lines.push('  readonly from: number')
  lines.push('  readonly to: number')
  lines.push('}')
  lines.push('')
  lines.push('export interface MigrationSource {')
  lines.push('  readonly version: number')
  lines.push('  readonly name: string')
  lines.push('  readonly checksum: string')
  lines.push('  readonly band: string')
  lines.push('  readonly sql: string')
  lines.push('}')
  lines.push('')
  lines.push('export const MIGRATION_BANDS: readonly MigrationBand[] = [')
  for (const band of BANDS) {
    lines.push(`  { id: ${JSON.stringify(band.id)}, label: ${JSON.stringify(band.label)}, from: ${band.from}, to: ${band.to} },`)
  }
  lines.push(']')
  lines.push('')
  lines.push('export const MIGRATION_SOURCES: Readonly<Record<MigrationKind, readonly MigrationSource[]>> = {')
  for (const kind of ['global', 'project']) {
    const sources = readSources(kind)
    lines.push(`  ${kind}: [`)
    for (const source of sources) {
      lines.push('    {')
      lines.push(`      version: ${source.version},`)
      lines.push(`      name: ${JSON.stringify(source.name)},`)
      lines.push(`      checksum: ${JSON.stringify(source.checksum)},`)
      lines.push(`      band: ${JSON.stringify(source.band)},`)
      lines.push(`      sql: ${JSON.stringify(source.sql)}`)
      lines.push('    },')
    }
    lines.push('  ],')
  }
  lines.push('}')
  lines.push('')
  lines.push('export const TARGET_VERSIONS: Readonly<Record<MigrationKind, number>> = {')
  for (const kind of ['global', 'project']) {
    const sources = readSources(kind)
    const target = sources.length === 0 ? 0 : sources[sources.length - 1].version
    lines.push(`  ${kind}: ${target},`)
  }
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

const content = renderBands()
const check = process.argv.includes('--check')
if (check) {
  let current = ''
  try {
    current = readFileSync(outFile, 'utf8')
  } catch {
    current = ''
  }
  if (current !== content) {
    console.error(`gen-bands: ${outFile} is stale; run node scripts/gen-bands.mjs`)
    process.exit(1)
  }
  console.log('gen-bands: bands.ts is up to date')
} else {
  writeFileSync(outFile, content)
  console.log(`gen-bands: wrote ${outFile}`)
}